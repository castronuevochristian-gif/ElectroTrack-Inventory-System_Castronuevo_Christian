    private void btnUpdateStockActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateStockActionPerformed
       int selectedRow = tblComponents.getSelectedRow();
    
    // Safety check: ensure a selection index was captured
    if (selectedRow == -1) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please click and highlight a component from the table first.", "Selection Required", javax.swing.JOptionPane.WARNING_MESSAGE);
        return;
    }

    // Capture specific cell item metadata variables out of the matching grid row array
    int compId = Integer.parseInt(tblComponents.getValueAt(selectedRow, 0).toString());
    String partNum = tblComponents.getValueAt(selectedRow, 1).toString();
    String currentQtyStr = tblComponents.getValueAt(selectedRow, 4).toString();

    // Spawn an input dialog window prompting the worker for data modification entries
    String input = javax.swing.JOptionPane.showInputDialog(this, "Enter updated inventory stock level for " + partNum + ":", currentQtyStr);
    
    if (input == null) return; 

    try {
        int newQty = Integer.parseInt(input.trim());
        if (newQty < 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "Stock quantities cannot drop below a 0 baseline.", "Validation Error", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        ComponentDAO compDAO = new ComponentDAO();
        if (compDAO.updateQuantity(compId, newQty)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Inventory quantity modified successfully!", "Success", javax.swing.JOptionPane.INFORMATION_MESSAGE);
            loadTableData(); 
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Failed to modify database record state.", "Database Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please enter a valid whole numerical index digit value.", "Format Error", javax.swing.JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnUpdateStockActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
     int selectedRow = tblComponents.getSelectedRow();
    
    if (selectedRow == -1) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please click and select an engineering component row to delete.", "Selection Required", javax.swing.JOptionPane.WARNING_MESSAGE);
        return;
    }

   
    int compId = Integer.parseInt(tblComponents.getValueAt(selectedRow, 0).toString());
    String partNum = tblComponents.getValueAt(selectedRow, 1).toString();
    String itemName = tblComponents.getValueAt(selectedRow, 2).toString();

   
    int confirmation = javax.swing.JOptionPane.showConfirmDialog(this, 
            "Are you absolutely sure you want to permanently delete " + partNum + " (" + itemName + ")?\nThis action cannot be undone.", 
            "Confirm Destructive Deletion", 
            javax.swing.JOptionPane.YES_NO_OPTION, 
            javax.swing.JOptionPane.WARNING_MESSAGE);

    if (confirmation == javax.swing.JOptionPane.YES_OPTION) {
        com.electrotrack.dao.ComponentDAO compDAO = new com.electrotrack.dao.ComponentDAO();
        if (compDAO.delete(compId)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Item successfully purged from structural inventory tracking.", "Record Purged", javax.swing.JOptionPane.INFORMATION_MESSAGE);
            loadTableData(); // Sync up the dashboard interface list row entries instantly
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Error processing execution query. Relational foreign key data ties might apply.", "Database Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }
    }//GEN-LAST:event_btnDeleteActionPerformed

