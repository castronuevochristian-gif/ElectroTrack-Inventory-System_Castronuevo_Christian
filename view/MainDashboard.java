    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        String keyword = txtSearch.getText().trim();

    // If empty, just fallback and refresh the data
    if (keyword.isEmpty()) {
        loadTableData();
        return;
    }

    // Execute standard database keyword query filter
    com.electrotrack.dao.ComponentDAO compDAO = new com.electrotrack.dao.ComponentDAO();
    java.util.List<com.electrotrack.model.Component> filteredItems = compDAO.search(keyword);

    // Update the JTable grid display with results
    populateTable(filteredItems);
    }//GEN-LAST:event_btnSearchActionPerformed

